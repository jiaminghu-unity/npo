#!/bin/bash
# One-off check (2026-11-12): is eval_sana.py --model_type sd15 equivalent to the user's original eval.py?
#   A: the original eval.py end to end on SD1.5 (base + Diffusion-DPO + Diffusion-KTO), seed 0, batch 16 as eval.sh
#   B: eval_sana.py's scorer on the images that A generated (same images, two scorers)
# Results: gs://prism-training-apac/jiaming/npo-sana/tests/orig-eval-check/ and ~/npo_sana_dev/tests/orig-eval-check/
set -uo pipefail
DIR="$(cd "$(dirname "$0")/.." && pwd)"
G=gs://prism-training-apac/jiaming/npo-sana
TAG=orig-eval-check
POOL=v
KEY="-i $HOME/.ssh/ray_worker_key -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR -o ConnectTimeout=20"
OUT="$DIR/tests/$TAG"; mkdir -p "$OUT"
log() { echo "$(date '+%m/%d %H:%M:%S') $*"; }

NODE="npo-test-$POOL-$(date +%d%H%M%S)"
log "creating node $NODE"
"$DIR/nodes/make_node.sh" "$NODE" "$POOL" || { log "CHECK_FAILED: could not get a GPU"; exit 1; }
ZONE=$(gcloud compute instances list --filter="name=$NODE" --format="value(zone.basename())")
IP=$(gcloud compute instances list --filter="name=$NODE" --format="value(networkInterfaces[0].networkIP)")
log "node $NODE ($ZONE, $IP)"
cleanup() { log "deleting node $NODE"; gcloud compute instances delete "$NODE" --zone "$ZONE" --quiet >/dev/null 2>&1; }
trap cleanup EXIT
for i in $(seq 1 60); do ssh $KEY ubuntu@$IP 'echo up' 2>/dev/null | grep -q up && break; sleep 10; done
for i in $(seq 1 90); do ssh $KEY ubuntu@$IP 'sudo grep -q NPO_NODE_READY /var/log/npo-startup.log' 2>/dev/null && break; sleep 10; done
log "node boot script finished"

cat > "$OUT/node_script.sh" <<EOF
#!/bin/bash
export HOME=/root TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD=1 TOKENIZERS_PARALLELISM=false
cd /root/npo
bash launchers/sana_setup_env.sh > /root/setup_main.log 2>&1 || { echo MAIN_SETUP_FAILED; exit 1; }
C=/root/check; mkdir -p \$C/out
PY=/root/sana-venv/bin/python
rm -rf eval_result_rebuttal
# A: the original eval.py, arguments as in eval.sh (epochs 'none' = load <repo>/unet)
\$PY /root/run_orig_eval.py --original_model stable-diffusion-v1-5/stable-diffusion-v1-5 \\
  --unet_checkpoints mhdang/dpo-sd1.5-text2image-v1 jacklishufan/diffusion-kto --epochs none none \\
  --names "Orig. SD1.5" "Diffusion-DPO" "Diffusion-KTO" \\
  --device_orig cuda:0 --device_trained cuda:0 --metrics_device cuda:0 --batch_size 16 --seed 0 \\
  --save_dir \$C/orig_images > \$C/out/A_stdout.log 2>&1 || { echo RUN_A_FAILED; exit 1; }
mv eval_result_rebuttal \$C/out/A_eval_result
echo "images generated by eval.py: \$(find \$C/orig_images -name '*.png' | wc -l)" > \$C/out/counts.txt
# B: eval_sana.py's scorer on exactly those images (they are found in the cache, nothing is generated)
\$PY eval_sana.py --model_type sd15 --unet_checkpoints mhdang/dpo-sd1.5-text2image-v1 jacklishufan/diffusion-kto \\
  --epochs none none --names "Orig. SD1.5" "Diffusion-DPO" "Diffusion-KTO" --seeds 0 --batch_size 32 \\
  --save_dir \$C/orig_images --result_dir \$C/out/B_my_scorer > \$C/out/B_stdout.log 2>&1 || { echo RUN_B_FAILED; exit 1; }
echo "images after eval_sana.py: \$(find \$C/orig_images -name '*.png' | wc -l); newer than A's results: \$(find \$C/orig_images -name '*.png' -newer \$C/out/counts.txt | wc -l)" >> \$C/out/counts.txt
gcloud storage rsync -r --quiet \$C/out $G/tests/$TAG/out >/dev/null 2>&1
echo CHECK_DONE
EOF

rsync -a --exclude .git --exclude __pycache__ --exclude output.log -e "ssh $KEY" ~/npo/ ubuntu@$IP:npo_src/ \
  && scp -q $KEY "$OUT/node_script.sh" "$DIR/orig_eval_check/run_orig_eval.py" ubuntu@$IP: \
  && ssh $KEY ubuntu@$IP "sudo rm -rf /root/npo && sudo cp -r ~/npo_src /root/npo && sudo cp ~/node_script.sh ~/run_orig_eval.py /root/ && sudo bash -c 'nohup bash /root/node_script.sh > /root/check.out 2>&1 &'" \
  || { log "CHECK_FAILED: could not start on the node"; exit 1; }
log "check started"
while true; do
  sleep 60
  st=$(ssh $KEY ubuntu@$IP "sudo cat /root/check.out 2>/dev/null | grep -o 'CHECK_DONE\|[A-Z0-9_]*FAILED' | tail -1" 2>/dev/null)
  if [ -n "$st" ]; then break; fi
  if ! gcloud compute instances describe "$NODE" --zone "$ZONE" --format="value(status)" 2>/dev/null | grep -q RUNNING; then
    st="NODE_LOST (spot preemption); rerun"; break
  fi
  prog=$(ssh $KEY ubuntu@$IP "sudo bash -c 'grep -a \"^Samples\" /root/check/out/A_stdout.log 2>/dev/null | tail -1; grep -a \"prompts\$\" /root/check/out/B_stdout.log 2>/dev/null | tail -1'" 2>/dev/null | tr '\n' ' ')
  log "running: $prog"
done
log "node finished with: $st"
ssh $KEY ubuntu@$IP "sudo bash -c 'tail -40 /root/check/out/A_stdout.log; echo ----B; tail -25 /root/check/out/B_stdout.log; echo ----setup; tail -5 /root/setup_main.log'" > "$OUT/log_tails.txt" 2>/dev/null
gcloud storage rsync -r --quiet "$G/tests/$TAG/out" "$OUT/out" >/dev/null 2>&1
if [ "$st" = CHECK_DONE ]; then log "CHECK_OK results in $OUT"; else log "CHECK_FAILED: $st"; fi
